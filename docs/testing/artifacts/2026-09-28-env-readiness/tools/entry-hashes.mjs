import { resolve } from "node:path";
import { createHash } from "node:crypto";
import { readFileSync, createReadStream, statSync } from "node:fs";
import JSZip from "jszip";
import { ActivitySpec } from "@leaplearn/shared";
import { compileToBuffer, createRegistry } from "./dist/index.js";
const root = resolve(import.meta.dirname, "../..");
const fixtures = resolve(import.meta.dirname, "test/fixtures");
const registry = await createRegistry({ lockPath: resolve(root, "libraries/libraries.lock.json"), cacheDir: resolve(root, "libraries/cache") });
const p = resolve(fixtures, "assets/card.jpg");
const card = { assetId: "card", sha256: createHash("sha256").update(readFileSync(p)).digest("hex"), byteLength: statSync(p).size, mimeType: "image/jpeg", open: () => createReadStream(p) };
const spec = ActivitySpec.parse(JSON.parse(readFileSync(resolve(fixtures, "specs/flashcards.json"), "utf8")));
const buf = await compileToBuffer(spec, new Map([["card", card]]), { registry, revision: 1 });
const zip = await JSZip.loadAsync(buf);
const lines = [];
for (const name of Object.keys(zip.files).sort()) lines.push(name + " " + createHash("sha256").update(await zip.files[name].async("nodebuffer")).digest("hex"));
console.log("node", process.versions.node, "zlib", process.versions.zlib, "arch", process.arch, "platform", process.platform);
console.log("package sha256 ", createHash("sha256").update(buf).digest("hex"));
console.log("entries        ", lines.length);
console.log("content sha256 ", createHash("sha256").update(lines.join("\n")).digest("hex"));
